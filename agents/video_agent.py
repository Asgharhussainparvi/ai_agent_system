"""
agents/video_agent.py
━━━━━━━━━━━━━━━━━━━━━
VideoAgent — builds the final video using a HYBRID strategy:

  AI video  (Motif-Video-2B)  ← used for KEY scenes (indices in AI_SCENE_INDICES)
  MoviePy   (slideshow)       ← used for ALL other scenes (full story flow)

The two clip types are concatenated in scene order, then audio is attached.

Fallback: pure MoviePy slideshow if Motif-Video fails entirely.
"""

from __future__ import annotations

import gc
from pathlib import Path
from typing import Dict, List, Optional

import torch

from utils.config import (
    AI_SCENE_INDICES,
    AUDIO_DIR,
    MOTIF_MODEL_ID,
    SD_DEVICE,
    SD_DTYPE,
    VIDEO_DIR,
    VIDEO_FPS,
    VIDEO_FRAMES,
)
from utils.logger import get_logger
from utils.retry import with_retry

_log = get_logger("VideoAgent")


class VideoAgent:
    """
    Hybrid video builder.

    Keyword args for run():
        image_paths  : List[Path]         scene images (in order)
        audio_path   : Optional[Path]     narration audio
        title        : str                video title (for prompts)
        content      : Optional[dict]     full ContentAgent output
    """

    OUTPUT_FILE = VIDEO_DIR / "final_video.mp4"

    # ── Motif-Video clip for a single scene ───────────────────────────────────
    def _motif_clip(self, prompt: str, scene_idx: int):
        """Return a MoviePy VideoClip generated by Motif-Video-2B, or None."""
        try:
            import numpy as np
            from diffusers import DiffusionPipeline
            from moviepy.editor import ImageSequenceClip

            _log.info("Motif-Video-2B: animating scene %d…", scene_idx + 1)
            pipe = DiffusionPipeline.from_pretrained(
                MOTIF_MODEL_ID, torch_dtype=SD_DTYPE, device_map=SD_DEVICE
            )
            output = pipe(
                f"{prompt}, smooth cinematic motion, professional video, high quality, 4k"
            )
            frames = [np.array(f) for f in output.images[0]]
            clip   = ImageSequenceClip(frames, fps=VIDEO_FPS)

            del pipe
            gc.collect()
            if torch.cuda.is_available():
                torch.cuda.empty_cache()

            return clip
        except Exception as exc:
            _log.warning("Motif-Video scene %d failed: %s — using image clip.", scene_idx + 1, exc)
            gc.collect()
            if torch.cuda.is_available():
                torch.cuda.empty_cache()
            return None

    # ── MoviePy still-image clip ──────────────────────────────────────────────
    @staticmethod
    def _image_clip(image_path: Path, duration: int = 5):
        from moviepy.editor import ImageClip
        return (
            ImageClip(str(image_path))
            .set_duration(duration)
            .resize((1280, 720))
            .set_fps(24)
        )

    # ── Full hybrid build ─────────────────────────────────────────────────────
    def _build_hybrid(
        self,
        image_paths: List[Path],
        audio_path: Optional[Path],
        content: Optional[dict],
    ) -> Optional[Path]:
        try:
            from moviepy.editor import AudioFileClip, concatenate_videoclips

            scenes      = (content or {}).get("scenes", [])
            img_prompts = (content or {}).get("image_prompts", [])
            clips       = []

            for idx, img_path in enumerate(image_paths):
                scene_info    = scenes[idx] if idx < len(scenes) else {}
                duration      = int(scene_info.get("duration_seconds", 5))
                scene_prompt  = img_prompts[idx] if idx < len(img_prompts) else "AI technology"

                if idx in AI_SCENE_INDICES:
                    # Attempt AI animation for key scenes
                    ai_clip = self._motif_clip(scene_prompt, idx)
                    if ai_clip:
                        # Stretch / trim to match scene duration
                        if ai_clip.duration < duration:
                            loops   = int(duration // ai_clip.duration) + 1
                            ai_clip = concatenate_videoclips([ai_clip] * loops).subclip(0, duration)
                        else:
                            ai_clip = ai_clip.subclip(0, duration)
                        clips.append(ai_clip)
                        _log.info("Scene %d: Motif-Video AI clip ✓", idx + 1)
                        continue

                # Default: static image clip (MoviePy)
                clips.append(self._image_clip(img_path, duration))
                _log.info("Scene %d: MoviePy image clip ✓", idx + 1)

            if not clips:
                return None

            video = concatenate_videoclips(clips, method="compose")

            # Attach narration audio
            if audio_path and audio_path.exists() and audio_path.stat().st_size > 0:
                audio = AudioFileClip(str(audio_path))
                if video.duration < audio.duration:
                    # Loop video to fill audio length
                    loops = int(audio.duration // video.duration) + 1
                    video = concatenate_videoclips([video] * loops).subclip(0, audio.duration)
                else:
                    video = video.subclip(0, audio.duration)
                video = video.set_audio(audio)

            _log.info("Rendering final video (%.1fs)…", video.duration)
            video.write_videofile(
                str(self.OUTPUT_FILE),
                fps=VIDEO_FPS,
                codec="libx264",
                audio_codec="aac",
                temp_audiofile=str(VIDEO_DIR / "tmp_audio.m4a"),
                remove_temp=True,
                logger=None,
            )
            _log.info("VideoAgent ✓  → %s", self.OUTPUT_FILE)
            return self.OUTPUT_FILE

        except Exception as exc:
            _log.error("Hybrid build failed: %s", exc)
            return None

    # ── Pure slideshow fallback ───────────────────────────────────────────────
    def _slideshow_fallback(
        self, image_paths: List[Path], audio_path: Optional[Path]
    ) -> Optional[Path]:
        try:
            from moviepy.editor import AudioFileClip, ImageClip, concatenate_videoclips

            _log.warning("Using pure slideshow fallback…")
            clips = [
                ImageClip(str(p)).set_duration(5).resize((1280, 720)).set_fps(24)
                for p in image_paths
            ]
            video = concatenate_videoclips(clips, method="compose")

            if audio_path and audio_path.exists() and audio_path.stat().st_size > 0:
                audio = AudioFileClip(str(audio_path))
                video = video.subclip(0, min(video.duration, audio.duration))
                video = video.set_audio(audio)

            video.write_videofile(
                str(self.OUTPUT_FILE), fps=24,
                codec="libx264", audio_codec="aac", logger=None,
            )
            return self.OUTPUT_FILE
        except Exception as exc:
            _log.error("Slideshow fallback also failed: %s", exc)
            return None

    # ── Main entry point ──────────────────────────────────────────────────────
    def run(
        self,
        image_paths: List[Path],
        audio_path: Optional[Path],
        title: str,
        content: Optional[dict] = None,
    ) -> Optional[Path]:
        result = self._build_hybrid(image_paths, audio_path, content)
        if result and result.exists():
            return result
        return self._slideshow_fallback(image_paths, audio_path)
